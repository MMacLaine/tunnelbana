// Bake the intro's metro geometry into src/intro.js (0.17.0). The source is the
// SL map's lines.geojson in the site repo (OSM real track geometry). The intro
// cannot fetch it: the itch build is a zip in an iframe, so the trimmed copy
// lives in the module itself, between the GEO markers.
//
// What is kept: the seven metro lines only, in Web Mercator pixels at zoom 12
// around T-Centralen, simplified to half a pixel and stored as integers of
// half pixels, delta encoded. Each stop keeps its distance along the line in
// metres, measured on the simplified line so the two can never disagree.
// Run: node _dev/bake-intro-geo.mjs [path/to/lines.geojson]
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const SRC = process.argv[2] || '/Users/matthewmaclaine/personal website/stockholm-sl-map/data/lines.geojson';
const OUT = join(ROOT, 'src/intro.js');

const W12 = 512 * 4096;
const mx = (lon) => (lon + 180) / 360;
const my = (lat) => (1 - Math.log(Math.tan(Math.PI / 4 + lat * Math.PI / 360)) / Math.PI) / 2;
const TC = [18.0597, 59.3313];
const px = (lon, lat) => [(mx(lon) - mx(TC[0])) * W12, (my(lat) - my(TC[1])) * W12];
// metres per pixel at zoom 12 on Stockholm's latitude
const MPP = 40075016.686 * Math.cos(TC[1] * Math.PI / 180) / W12;
const TOL = 0.5; // pixels at zoom 12

function rdp(pts, tol) {
  if (pts.length < 3) return pts.slice();
  const keep = new Uint8Array(pts.length); keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    let best = -1, bi = -1;
    const [ax, ay] = pts[a], [bx, by] = pts[b], dx = bx - ax, dy = by - ay, L = Math.hypot(dx, dy) || 1;
    for (let i = a + 1; i < b; i++) {
      const d = Math.abs((pts[i][0] - ax) * dy - (pts[i][1] - ay) * dx) / L;
      if (d > best) { best = d; bi = i; }
    }
    if (best > tol) { keep[bi] = 1; stack.push([a, bi], [bi, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}
// distance along a polyline of the point nearest to p
function along(line, p) {
  let best = Infinity, at = 0, run = 0;
  for (let i = 0; i + 1 < line.length; i++) {
    const [ax, ay] = line[i], [bx, by] = line[i + 1], dx = bx - ax, dy = by - ay, L2 = dx * dx + dy * dy || 1;
    const q = Math.max(0, Math.min(1, ((p[0] - ax) * dx + (p[1] - ay) * dy) / L2));
    const d = Math.hypot(ax + dx * q - p[0], ay + dy * q - p[1]);
    if (d < best) { best = d; at = run + q * Math.sqrt(L2); }
    run += Math.sqrt(L2);
  }
  return at;
}

const geo = JSON.parse(readFileSync(SRC, 'utf8'));
const lines = [];
for (const f of geo.features) {
  const p = f.properties;
  if (p.mode !== 'metro' || f.geometry.type !== 'LineString') continue;
  const c = f.geometry.coordinates;
  const full = c.map((q) => px(q[0], q[1]));
  // where each stop sits on the original line (its third coordinate is metres along it)
  const stopAt = (d) => {
    for (let i = 0; i + 1 < c.length; i++) {
      if (c[i + 1][2] >= d) { const q = (d - c[i][2]) / ((c[i + 1][2] - c[i][2]) || 1); return [full[i][0] + (full[i + 1][0] - full[i][0]) * q, full[i][1] + (full[i + 1][1] - full[i][1]) * q]; }
    }
    return full[full.length - 1];
  };
  const simple = rdp(full, TOL).map(([x, y]) => [Math.round(x * 2), Math.round(y * 2)]);
  const half = simple.map(([x, y]) => [x / 2, y / 2]);
  const enc = [];
  simple.forEach(([x, y], i) => { if (i) enc.push(x - simple[i - 1][0], y - simple[i - 1][1]); else enc.push(x, y); });
  const stops = p.stops.map(([d, name]) => [Math.round(along(half, stopAt(d)) * MPP), name]);
  lines.push([p.key, enc, stops]);
}
const block = '/* GEO:BEGIN generated by _dev/bake-intro-geo.mjs from the SL map lines.geojson, do not edit by hand */\n' +
  'const GEO = ' + JSON.stringify({ mpp: +MPP.toFixed(5), lines }) + ';\n/* GEO:END */';
const src = readFileSync(OUT, 'utf8');
const re = /\/\* GEO:BEGIN[\s\S]*?\/\* GEO:END \*\//;
if (!re.test(src)) throw new Error('no GEO markers in src/intro.js');
writeFileSync(OUT, src.replace(re, block));
console.log('baked', lines.length, 'lines,', lines.reduce((n, L) => n + L[1].length / 2, 0), 'points,', block.length, 'bytes');
